
/*
  Регіон покупця — від нього залежить ЦІНА, тоді як від мови залежить лише
  ВАЛЮТА показу. Це навмисно різні речі.

  Якби ціну визначала мова, українець, який перемкнув сайт на англійську
  просто подивитись, миттю побачив би дорожчий товар. А іноземець, який читає
  українською, платив би внутрішню ціну й не покрив пересилку.

  Чому cookie, а не лише IP. Країну з IP Vercel підказує заголовком
  `x-vercel-ip-country`, але помиляється на VPN, на мобільних операторах і
  на всіх українцях за кордоном — а їх багато: людина з Варшави замовляє
  мамі в Київ. Тому IP лише ПІДКАЗУЄ початкове значення, а остаточно вирішує
  сам покупець перемикачем, і його вибір лежить у cookie.

  Cookie доходить і до сторінок, і до роутів кошика й оплати — на відміну від
  заголовка мови, який ставить middleware, а він у /api не заходить. Через це
  cookie тут єдине джерело правди.

  Довіряти їй на оплаті не можна: cookie правиться з браузера. Тому на
  оформленні регіон ще раз виводиться зі способу доставки — див.
  `regionForOrder` у checkout.
*/

export const REGION_COOKIE = 'mk.region.v1'

