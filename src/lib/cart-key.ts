/**
 * Ключ позиції в кошику.
 *
 * Формат жив у шести місцях одночасно: у двох гілках API кошика, у кнопці
 * курсу, у кнопці товару, у наборах до товару й у блоці «може сподобатись».
 * Шість копій одного рядка — це шість способів розійтися: досить одній
 * поставити `base` там, де інша ставить айді варіації, і той самий товар
 * ляже в кошик двічі окремими позиціями.
 *
 * Чому саме так:
 *
 * - курс один, варіацій у нього не буває — досить `course:12`;
 * - товар різниться варіацією, тож `product:7:3`. Коли варіацій немає зовсім,
 *   підставляємо `base`, інакше ключ закінчувався б двокрапкою й два різні
 *   стани виглядали б однаково.
 */
export const cartKey = (
  kind: 'product' | 'course',
  id: string | number,
  variantId?: string | number | null,
): string => (kind === 'course' ? `course:${id}` : `product:${id}:${variantId ?? 'base'}`)
