'use client'

import { useEffect } from 'react'

import { useCart } from '@/providers/CartProvider'

/*
  Кошик спорожняємо після підтвердженої оплати, а не перед переходом на неї.

  Раніше форма чистила його одразу, як тільки створила замовлення — тобто ще
  до того, як людина побачила сторінку банку. Хто передумав або в кого не
  пройшла картка, повертався на сайт із порожнім кошиком і мусив набирати все
  заново.

  Чистити на сервері не можна: браузер тримає копію в localStorage і, побачивши
  на сервері порожньо, одразу заливає її назад. Тому робимо це тут, на стороні
  клієнта — звідси очищення розходиться і в сховище, і на сервер.
*/
export const ClearCartOnPaid = () => {
  const { clear, ready } = useCart()

  /*
    Чекаємо на ready. Провайдер спершу малює те, що лишилось у браузері, а
    потім підтягує кошик із сервера — і якщо почистити до того, відповідь
    сервера просто поверне все назад. Саме так і виходило: замовлення
    оплачене, а кошик знову повний.
  */
  useEffect(() => {
    if (ready) clear()
  }, [ready, clear])

  return null
}
