import type { Field } from 'payload'

/*
  Ціни двома блоками: своїм для України і своїм для закордону.

  Доти всі чотири поля стояли підряд одним стовпчиком — «Ціна», «Ціна для
  закордону», «Стара ціна», «Стара ціна для закордону». Який із двох «старих»
  до якої ціни належить, доводилось зчитувати з підпису, і помилитись було
  легко: вписали знижку в закордонне поле — українець її не бачить, і ніхто
  цього не помічає, поки не поскаржиться покупець.

  Тепер у кожного регіону своя рамка, і поруч у ній рівно його пара: ціна й
  закреслена ціна.

  `collapsible`, а не `group`: group склав би значення в окремий обʼєкт і
  змінив імена полів у базі, тобто зажадав би міграції й правок усюди, де ці
  ціни читаються. Рамка потрібна лише для ока.
*/
export const priceFields = (options: {
  /** Чим відрізняється базова ціна в цій колекції. */
  baseHint: string
  /** Чим відрізняється закордонна. */
  exportHint?: string
}): Field[] => [
  {
    type: 'collapsible',
    label: 'Ціни для України',
    admin: { initCollapsed: false },
    fields: [
      {
        type: 'row',
        fields: [
          {
            name: 'price',
            type: 'number',
            label: 'Ціна, ₴',
            required: true,
            min: 0,
            admin: { width: '50%', description: options.baseHint },
          },
          {
            name: 'oldPrice',
            type: 'number',
            label: 'Стара ціна, ₴',
            min: 0,
            admin: {
              width: '50%',
              description: 'Закреслена поруч зі звичайною. Порожньо — знижки немає.',
            },
          },
        ],
      },
    ],
  },
  {
    type: 'collapsible',
    label: 'Ціни для закордону',
    admin: { initCollapsed: false },
    fields: [
      {
        type: 'row',
        fields: [
          {
            name: 'priceExport',
            type: 'number',
            label: 'Ціна, ₴',
            min: 0,
            admin: {
              width: '50%',
              description:
                options.exportHint ??
                'Сюди закладають пересилку — за кордоном на сайті пишеться «безкоштовна доставка». Порожньо — беремо українську ціну.',
            },
          },
          {
            name: 'oldPriceExport',
            type: 'number',
            label: 'Стара ціна, ₴',
            min: 0,
            admin: {
              width: '50%',
              description:
                'Порожньо — за кордоном знижки не показуємо. Українську сюди НЕ підставляємо: закордонна ціна вища, і закреслена українська виглядала б як подорожчання, подане знижкою.',
            },
          },
        ],
      },
    ],
  },
]
